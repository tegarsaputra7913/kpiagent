#include <stdio.h>

int main() {
    float A, B, SUM;

    // Step-2: Input first number say A
    printf("Input Value of A: ");
    scanf("%f", &A);

    // Step-3: Input second number say B
    printf("Input Value of B: ");
    scanf("%f", &B);

    // Step-4: SUM = A + B
    SUM = A + B;

    // Step-5: Display SUM
    printf("SUM = %f\n", SUM);

    return 0; // Step-6: Stop
}
